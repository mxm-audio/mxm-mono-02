/// What a route's amount reads: **what that pair delivers**, in the target's own unit — so the
/// machine's own routes read the machine's numbers at full, the envelope's negative half included
/// (`routing::scale`), and a route the SH-2 never had reads the collection's standard reach. The
/// key's unit is six octaves, so a Key route reads per octave of key.
fn reach(target: usize, source: usize) -> Reach {
    let unit = match target {
        target::PITCH => reading::SEMITONES,
        target::CUTOFF => reading::OCTAVES,
        _ => reading::PERCENT,
    };
    let (above, below) = (
        routing::scale(target, source, 1.0),
        routing::scale(target, source, -1.0),
    );
    if source == source::KEY {
        let per_octave = 12.0 / KEY_UNIT_SEMITONES;
        Reach::per_octave(above * per_octave, unit).below(below * per_octave)
    } else {
        Reach::new(above, unit).below(below)
    }
}

/// A route amount: signed, centred on zero, and **an amount, so it starts there** — the
/// collection's one route parameter (`mxm_modulation_params::reading`), on the travel the pair's
/// offer allows, which on this instrument is always both halves. Smoothed at the 10 ms the controls
/// it replaced had, because it multiplies a signal.
fn amount(target: usize, source: usize) -> FloatParam {
    reading::amount_param(
        format!("{} from {}", TARGET_NAMES[target], SOURCE_NAMES[source]),
        reach(target, source),
        Fader::for_offer(offer(target, source), false),
        10.0,
    )
}

/// Whether a route exists. **Configuration, not an amount**, so its default is the machine's own
/// wiring: six of the eight paths the SH-2 hard-wired that are still here are present in the init
/// patch, at zero depth — all but the pulse width's two, which the owner took off the Init stack
/// (2026-09-27) and which a design that uses them switches on.
fn present(target: usize, source: usize) -> BoolParam {
    BoolParam::new(
        format!("{} from {} on", TARGET_NAMES[target], SOURCE_NAMES[source]),
        INIT_PRESENT.contains(&(target, source)),
    )
}

