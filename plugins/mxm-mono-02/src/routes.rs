    /// **A route reads what its pair delivers**, in the target's unit, the machine's numbers at full
    /// — and a reading typed back in lands on the amount it came from.
    #[test]
    fn a_route_reads_what_its_pair_delivers_and_reads_back() {
        use mxm_preset::ErasedParam;
        let r = Routes::new();
        let cases: [(&FloatParam, f32, &str); 15] = [
            // The machine's own, at their controls' reach.
            (&r.pitch.lfo, 1.0, "+7.00 st"),
            (&r.pitch.autobend, 1.0, "-12.00 st"),
            (&r.width.lfowidth, 1.0, "-45 %"),
            (&r.width.env, 1.0, "-45 %"),
            (&r.cutoff.env, 1.0, "+10.00 oct"),
            (&r.cutoff.env, 0.0, "-2.75 oct"),
            (&r.cutoff.lfo, 1.0, "+4.00 oct"),
            (&r.cutoff.key, 1.0, "+1.20 oct/oct"),
            (&r.cutoff.bend, 1.0, "+2.00 oct"),
            // Added ones, at the collection's standard reach.
            (&r.pitch.key, 1.0, "+12.00 st/oct"),
            (&r.pitch.wheel, 1.0, "+12.00 st"),
            (&r.cutoff.vel, 1.0, "+4.00 oct"),
            (&r.width.key, 1.0, "-9 %/oct"),
            (&r.amp.vel, 1.0, "+100 %"),
            (&r.amp.key, 1.0, "+20 %/oct"),
        ];
        for (param, normalised, expected) in cases {
            let text = ErasedParam::format(param, normalised);
            assert_eq!(
                text,
                expected,
                "{} at {normalised}",
                ErasedParam::name(param)
            );
            let back = param
                .string_to_normalized_value(&text)
                .expect("the reading parses");
            assert!(
                (back - normalised).abs() < 1e-3,
                "{}: {text} read back as {back}",
                ErasedParam::name(param)
            );
        }
    }

